"""Write docs/verification/README.md from the verification JSON files in that folder.

Every number in the index is read from a JSON file here; nothing is typed by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

VERIFICATION_DIR = Path("docs/verification")


def load(name: str) -> dict[str, Any]:
    """Read one verification JSON."""
    data: dict[str, Any] = json.loads((VERIFICATION_DIR / name).read_text(encoding="utf-8"))
    return data


def main() -> int:
    """Build the index."""
    bat = load("leakage_battery.json")
    pre = load("leakage_battery_pre_fix.json")
    rep = load("baseline_reproduction.json")
    leak = load("batch_leak.json")
    intake = load("colab_checkpoint_intake.json")
    val = load("validation_comparison.json")

    a, b, c, e = bat["a_brute_force"], bat["b_injection"], bat["c_ties"], bat["e_ablation"]
    sizes = [k for k in b if k.startswith("bs")]
    before, after = pre["e_ablation"]["full_model"], e["full_model"]
    pre_b = pre["b_injection"]
    leak_lines = [
        f"{m['name']}: weighted PR-AUC {m['batch_sizes']['2048']['pr_auc_weighted']:.4f} at batch "
        f"2048 vs {m['batch_sizes']['1']['pr_auc_weighted']:.4f} at batch 1"
        for m in leak["models"].values()
    ]
    scored = {r["key"]: r for r in val["models"] if r.get("status") == "scored"}

    rows = [
        (
            "leakage_battery.json",
            "Leakage battery on real validation data, fixed loader (checks a-e)",
            "scripts/leakage_battery.py",
            f"gate {'PASS' if bat['gate_pass'] else 'FAIL'}; {c['sampled_edges_checked']:,} sampled "
            f"edges, {c['edges_at_or_after_target_time']} at/after target time, "
            f"{c['own_edges_present']} own edges; brute-force max score diff "
            f"{a['max_score_abs_diff']:.1e}; injection bit-identical at batch sizes "
            f"{', '.join(k[2:] for k in sizes)}; no message passing {e['no_message_passing']:.4f} "
            f"vs full {e['full_model']:.4f}",
        ),
        (
            "leakage_battery_pre_fix.json",
            "Same battery before the float64 fix (global float32 amount cumsum)",
            "scripts/leakage_battery.py (pre-fix loader)",
            f"gate {'PASS' if pre['gate_pass'] else 'FAIL'}: check b) earlier targets changed by up "
            f"to {pre_b[sizes[0]]['early_max_abs_diff']:.4f} under injection",
        ),
        (
            "baseline_reproduction.json",
            "Retrained oracle XGBoost and MLP (original code, config, seed)",
            "scripts/reproduce_baselines.py",
            "; ".join(
                f"{k}: test PR-AUC {v['retrained_test_pr_auc']:.4f}, signed difference vs original "
                f"{v['retrained_test_pr_auc'] - v['original_test_pr_auc']:+.1e}, val PR-AUC "
                f"{v['val_pr_auc']:.4f}"
                for k, v in rep.items()
            ),
        ),
        (
            "batch_leak.json",
            "Batch-sharing leak: same rows scored at batch sizes 1/16/128/2048 (pre-fix loader)",
            "scripts/measure_batch_leak.py",
            "; ".join(leak_lines),
        ),
        (
            "colab_checkpoint_intake.json",
            "Colab checkpoint intake: hashes, epoch, history, strict load",
            "scripts/intake_colab_checkpoint.py",
            f"epoch {intake['best_epoch']} of a run stopped at epoch {intake['state_last_epoch']}, "
            f"val PR-AUC {intake['best_val_pr_auc']:.4f}, weights sha256 "
            f"{intake['output_sha256'][:12]}...",
        ),
        (
            "validation_comparison.json",
            "Validation PR-AUC of all models on the same rows (GNN rows: pre-fix loader)",
            "scripts/validation_comparison.py",
            "; ".join(f"{k} {r['val_pr_auc']:.4f}" for k, r in scored.items()),
        ),
    ]
    md = [
        "# Verification evidence",
        "",
        "Generated by `scripts/make_verification_index.py` from the JSON files in this folder. "
        "Large prediction files stay in `data/processed/` (not committed).",
        "",
        "| File | Check | Regenerate with | Headline |",
        "|---|---|---|---|",
        *[f"| `{f}` | {check} | `{script}` | {head} |" for f, check, script, head in rows],
        "",
        "## Float32 amount-sum fix",
        "",
        f"Validation PR-AUC of the isolated-batch HeteroGAT: {before:.10f} before the fix, "
        f"{after:.10f} after (|difference| {abs(after - before):.1e}). The float32 defect did not "
        "contribute to the score.",
        "",
    ]
    (VERIFICATION_DIR / "README.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
